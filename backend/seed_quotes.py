def seed_quotes(db) -> int:
    """首次导入台词（幂等：表内已有数据则整体跳过，不覆盖后台增删改的结果）"""
    if db.query(Quote).count() > 0:
        return 0
    for order, (text, source) in enumerate(DEFAULT_QUOTES):
        db.add(Quote(text=text, source=source, enabled=1, sort_order=order))
    db.commit()
    return len(DEFAULT_QUOTES)
